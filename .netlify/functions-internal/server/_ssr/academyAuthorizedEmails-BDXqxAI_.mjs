var CONFIRMED_EMAILS_SET = new Set(CONFIRMED_ACADEMY_EMAILS);
var CONFIRMED_USERNAMES_SET = new Set(CONFIRMED_ACADEMY_EMAILS.map((email) => email.split("@")[0].toLowerCase()));
/**
* Normalizes an email for lookup:
* - trims and converts to lower case
* - handles apostrophe normalization (e.g. ng'ang'a vs nganga)
*/
function normalizeAcademyEmail(email) {
	return email.trim().toLowerCase();
}
/**
* Extracts a friendly display name from the email (e.g., "cheryl.cosmas" -> "Cheryl Cosmas")
*/
function getEmailDisplayName(email) {
	const norm = normalizeAcademyEmail(email);
	return (norm.includes("@") ? norm.split("@")[0] : norm).split(".").map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join(" ");
}
/**
* Confirms whether the provided email exists in the official authorized academy roster.
* Checks both the exact email and username against the confirmed roster.
*/
function isEmailInConfirmedList(email) {
	if (!email || typeof email !== "string") return false;
	const normalized = normalizeAcademyEmail(email);
	if (!normalized.includes("@")) return false;
	if (CONFIRMED_EMAILS_SET.has(normalized)) return true;
	const deApostrophed = normalized.replace(/['`]/g, "");
	for (const confirmed of CONFIRMED_EMAILS_SET) if (confirmed.replace(/['`]/g, "") === deApostrophed) return true;
	const [user, domain] = normalized.split("@");
	if (domain === "mpesafoundationacademy.ac.ke" || domain === "mpesa.ac.ke") {
		const cleanUser = user.replace(/['`]/g, "");
		for (const u of CONFIRMED_USERNAMES_SET) if (u.replace(/['`]/g, "") === cleanUser) return true;
	}
	return false;
}
